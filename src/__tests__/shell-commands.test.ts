async function run(line: string) {
  const volume = new MemoryVolume();
  for (const [path, content] of Object.entries(FIXTURE)) {
    const full = `/w/${path}`;
    volume.mkdirSync(full.slice(0, full.lastIndexOf("/")), { recursive: true });
    volume.writeFileSync(full, content);
  }
  volume.mkdirSync("/home/user", { recursive: true });
  const shell = new NodepodShell(volume, { cwd: "/w", env: { PATH: "/usr/bin", PWD: "/w", HOME: "/home/user", TZ: "UTC" } });
  // stdout and stderr go to files, as they went to pipes in bash
  const result = await shell.exec(`{ ${line}\n} > /home/user/out 2> /home/user/err`);
  return {
    stdout: volume.readFileSync("/home/user/out", "utf8") as string,
    stderr: volume.readFileSync("/home/user/err", "utf8") as string,
    exitCode: result.exitCode,
  };
}

describe("commands against bash 5 and GNU coreutils", () => {
  it.each(CASES)("%s", async (line, stdout, exitCode, wroteStderr) => {
    const result = await run(line);
    expect(result.stdout).toBe(stdout);
    expect(result.exitCode).toBe(exitCode);
    expect(result.stderr !== "").toBe(wroteStderr);
  });
});
